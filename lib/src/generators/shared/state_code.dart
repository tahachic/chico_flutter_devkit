import '../../config/models.dart';
import '../../fs/write_plan.dart';
import '../../naming/name_converter.dart';
import '../feature/feature_layout.dart';

/// Shared state-management file builders used by feature + dedicated generators.
abstract final class StateCode {
  static List<PlannedFileWrite> build({
    required NormalizedName name,
    required StateManagement state,
    required String project,
    required Architecture architecture,
    String? featureSnake,
    bool generateTests = false,
  }) {
    final featureName = featureSnake == null
        ? null
        : NameConverter.parse(featureSnake);
    final layout = FeatureLayout(
      architecture: architecture,
      name: featureName ?? name,
    );

    final subject = name;
    final dir = featureSnake == null
        ? _standaloneDir(state)
        : layout.stateDir(state);

    final writes = List<PlannedFileWrite>.from(switch (state) {
      StateManagement.bloc => _blocFiles(
        dir: dir,
        subject: subject,
        entityImport: _entityImport(project, layout, featureSnake),
        useCaseImport: _useCaseImport(project, layout, featureSnake),
      ),
      StateManagement.cubit => _cubitFiles(
        dir: dir,
        subject: subject,
        entityImport: _entityImport(project, layout, featureSnake),
        useCaseImport: _useCaseImport(project, layout, featureSnake),
      ),
      StateManagement.riverpod => _riverpodFiles(
        dir: dir,
        subject: subject,
        entityImport: _entityImport(project, layout, featureSnake),
        repositoryImport: _repositoryImport(project, layout, featureSnake),
        useCaseImport: _useCaseImport(project, layout, featureSnake),
      ),
      StateManagement.provider => _providerFiles(
        dir: dir,
        subject: subject,
        entityImport: _entityImport(project, layout, featureSnake),
        useCaseImport: _useCaseImport(project, layout, featureSnake),
      ),
    });

    if (generateTests) {
      writes.add(
        PlannedFileWrite(
          relativePath: featureSnake == null
              ? 'test/${_standaloneTestDir(state)}/${subject.snakeCase}_${state.yamlValue}_test.dart'
              : 'test/features/${layout.snake}/${subject.snakeCase}_${state.yamlValue}_test.dart',
          content: _stateTest(subject: subject, state: state),
        ),
      );
    }

    return writes;
  }

  static String _standaloneDir(StateManagement state) {
    final folder = switch (state) {
      StateManagement.bloc => 'bloc',
      StateManagement.cubit => 'cubit',
      StateManagement.riverpod || StateManagement.provider => 'providers',
    };
    return 'lib/presentation/$folder';
  }

  static String _standaloneTestDir(StateManagement state) {
    return switch (state) {
      StateManagement.bloc => 'bloc',
      StateManagement.cubit => 'cubit',
      StateManagement.riverpod || StateManagement.provider => 'providers',
    };
  }

  static String? _entityImport(
    String project,
    FeatureLayout layout,
    String? featureSnake,
  ) {
    if (featureSnake == null) return null;
    return layout.packageImport(project, layout.entity);
  }

  static String? _useCaseImport(
    String project,
    FeatureLayout layout,
    String? featureSnake,
  ) {
    if (featureSnake == null) return null;
    return layout.packageImport(project, layout.getUseCase);
  }

  static String? _repositoryImport(
    String project,
    FeatureLayout layout,
    String? featureSnake,
  ) {
    if (featureSnake == null) return null;
    return layout.packageImport(project, layout.repositoryContract);
  }

  static List<PlannedFileWrite> _blocFiles({
    required String dir,
    required NormalizedName subject,
    required String? entityImport,
    required String? useCaseImport,
  }) {
    final pascal = subject.pascalCase;
    final snake = subject.snakeCase;
    final entityType = entityImport == null ? 'Object' : pascal;
    final getListType = entityImport == null
        ? 'Future<List<$entityType>> Function()'
        : 'Get${pascal}List';

    return [
      PlannedFileWrite(
        relativePath: '$dir/${snake}_event.dart',
        content:
            '''
/// Generated by Chico Flutter DevKit — bloc events
sealed class ${pascal}Event {
  const ${pascal}Event();
}

final class ${pascal}Started extends ${pascal}Event {
  const ${pascal}Started();
}

final class ${pascal}Refreshed extends ${pascal}Event {
  const ${pascal}Refreshed();
}
''',
      ),
      PlannedFileWrite(
        relativePath: '$dir/${snake}_state.dart',
        content:
            '''
${entityImport ?? ''}

/// Generated by Chico Flutter DevKit — bloc states
sealed class ${pascal}State {
  const ${pascal}State();
}

final class ${pascal}Initial extends ${pascal}State {
  const ${pascal}Initial();
}

final class ${pascal}Loading extends ${pascal}State {
  const ${pascal}Loading();
}

final class ${pascal}Loaded extends ${pascal}State {
  const ${pascal}Loaded(this.items);

  final List<$entityType> items;
}

final class ${pascal}Failure extends ${pascal}State {
  const ${pascal}Failure(this.message);

  final String message;
}
''',
      ),
      PlannedFileWrite(
        relativePath: '$dir/${snake}_bloc.dart',
        content:
            '''
import 'package:flutter_bloc/flutter_bloc.dart';

${useCaseImport ?? ''}
import '${snake}_event.dart';
import '${snake}_state.dart';

/// Generated by Chico Flutter DevKit — bloc
class ${pascal}Bloc extends Bloc<${pascal}Event, ${pascal}State> {
  ${pascal}Bloc(this._getList) : super(const ${pascal}Initial()) {
    on<${pascal}Started>(_onStarted);
    on<${pascal}Refreshed>(_onStarted);
  }

  final $getListType _getList;

  Future<void> _onStarted(
    ${pascal}Event event,
    Emitter<${pascal}State> emit,
  ) async {
    emit(const ${pascal}Loading());
    try {
      final items = await _getList();
      emit(${pascal}Loaded(items));
    } catch (error) {
      emit(${pascal}Failure(error.toString()));
    }
  }
}
''',
      ),
    ];
  }

  static List<PlannedFileWrite> _cubitFiles({
    required String dir,
    required NormalizedName subject,
    required String? entityImport,
    required String? useCaseImport,
  }) {
    final pascal = subject.pascalCase;
    final snake = subject.snakeCase;
    final entityType = entityImport == null ? 'Object' : pascal;
    final getListType = entityImport == null
        ? 'Future<List<$entityType>> Function()'
        : 'Get${pascal}List';

    return [
      PlannedFileWrite(
        relativePath: '$dir/${snake}_state.dart',
        content:
            '''
${entityImport ?? ''}

/// Generated by Chico Flutter DevKit — cubit states
sealed class ${pascal}State {
  const ${pascal}State();
}

final class ${pascal}Initial extends ${pascal}State {
  const ${pascal}Initial();
}

final class ${pascal}Loading extends ${pascal}State {
  const ${pascal}Loading();
}

final class ${pascal}Loaded extends ${pascal}State {
  const ${pascal}Loaded(this.items);

  final List<$entityType> items;
}

final class ${pascal}Failure extends ${pascal}State {
  const ${pascal}Failure(this.message);

  final String message;
}
''',
      ),
      PlannedFileWrite(
        relativePath: '$dir/${snake}_cubit.dart',
        content:
            '''
import 'package:flutter_bloc/flutter_bloc.dart';

${useCaseImport ?? ''}
import '${snake}_state.dart';

/// Generated by Chico Flutter DevKit — cubit
class ${pascal}Cubit extends Cubit<${pascal}State> {
  ${pascal}Cubit(this._getList) : super(const ${pascal}Initial());

  final $getListType _getList;

  Future<void> load() async {
    emit(const ${pascal}Loading());
    try {
      final items = await _getList();
      emit(${pascal}Loaded(items));
    } catch (error) {
      emit(${pascal}Failure(error.toString()));
    }
  }
}
''',
      ),
    ];
  }

  static List<PlannedFileWrite> _riverpodFiles({
    required String dir,
    required NormalizedName subject,
    required String? entityImport,
    required String? repositoryImport,
    required String? useCaseImport,
  }) {
    final pascal = subject.pascalCase;
    final snake = subject.snakeCase;
    final entityType = entityImport == null ? 'Object' : pascal;

    if (entityImport == null) {
      return [
        PlannedFileWrite(
          relativePath: '$dir/${snake}_providers.dart',
          content:
              '''
import 'package:flutter_riverpod/flutter_riverpod.dart';

/// Generated by Chico Flutter DevKit — riverpod providers
final ${snake}ListProvider = FutureProvider<List<$entityType>>((ref) async {
  throw UnimplementedError('Wire $pascal data loading.');
});
''',
        ),
      ];
    }

    return [
      PlannedFileWrite(
        relativePath: '$dir/${snake}_providers.dart',
        content:
            '''
import 'package:flutter_riverpod/flutter_riverpod.dart';

$entityImport
$useCaseImport
$repositoryImport

/// Generated by Chico Flutter DevKit — riverpod providers
final ${snake}RepositoryProvider = Provider<${pascal}Repository>((ref) {
  throw UnimplementedError('Bind ${pascal}Repository in the composition root.');
});

final get${pascal}ListProvider = Provider<Get${pascal}List>((ref) {
  return Get${pascal}List(ref.watch(${snake}RepositoryProvider));
});

final ${snake}ListProvider = FutureProvider<List<$entityType>>((ref) {
  return ref.watch(get${pascal}ListProvider)();
});
''',
      ),
    ];
  }

  static List<PlannedFileWrite> _providerFiles({
    required String dir,
    required NormalizedName subject,
    required String? entityImport,
    required String? useCaseImport,
  }) {
    final pascal = subject.pascalCase;
    final snake = subject.snakeCase;
    final entityType = entityImport == null ? 'Object' : pascal;
    final getListType = entityImport == null
        ? 'Future<List<$entityType>> Function()'
        : 'Get${pascal}List';

    return [
      PlannedFileWrite(
        relativePath: '$dir/${snake}_provider.dart',
        content:
            '''
import 'package:flutter/foundation.dart';

${entityImport ?? ''}
${useCaseImport ?? ''}

/// Generated by Chico Flutter DevKit — ChangeNotifier provider
class ${pascal}Provider extends ChangeNotifier {
  ${pascal}Provider(this._getList);

  final $getListType _getList;

  bool loading = false;
  String? error;
  List<$entityType> items = const [];

  Future<void> load() async {
    loading = true;
    error = null;
    notifyListeners();
    try {
      items = await _getList();
    } catch (err) {
      error = err.toString();
    } finally {
      loading = false;
      notifyListeners();
    }
  }
}
''',
      ),
    ];
  }

  static String _stateTest({
    required NormalizedName subject,
    required StateManagement state,
  }) {
    final pascal = subject.pascalCase;
    return '''
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('$pascal ${state.yamlValue} scaffolding exists', () {
    expect('$pascal', isNotEmpty);
  });
}
''';
  }
}
