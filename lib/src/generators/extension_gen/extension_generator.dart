import '../../core/exceptions.dart';
import '../../fs/write_plan.dart';
import '../context.dart';
import '../result.dart';
import '../runner.dart';
import '../shared/generator_options.dart';

/// Generates a Dart extension on a target type.
final class ExtensionGenerator extends BaseGenerator {
  @override
  String get name => 'extension';

  @override
  String get description => 'Generate a Dart extension (use --on Type).';

  @override
  Future<void> validate(GenerationContext context) async {
    final onType = context.extra['on'] as String?;
    if (onType == null || onType.trim().isEmpty) {
      throw const InvalidUsageException(
        'Extension target type is required.',
        details: 'Example: devkit generate extension StringX --on String',
      );
    }
  }

  @override
  Future<GenerationResult> generate(GenerationContext context) async {
    final extensionName = context.targetName.pascalCase;
    final snake = context.targetName.snakeCase;
    final onType = (context.extra['on'] as String).trim();
    final generateTests = GeneratorOptions.wantsTests(context);

    final writes = <PlannedFileWrite>[
      PlannedFileWrite(
        relativePath: 'lib/extensions/$snake.dart',
        content:
            '''
/// Generated by Chico Flutter DevKit — extension:$extensionName
extension $extensionName on $onType {
  /// Returns true when the value is considered empty for this type.
  bool get isBlank {
${_isBlankBody(onType)}
  }
}
''',
      ),
    ];

    if (generateTests) {
      writes.add(
        PlannedFileWrite(
          relativePath: 'test/extensions/${snake}_test.dart',
          content: _test(
            project: context.config.project.name,
            snake: snake,
            extensionName: extensionName,
            onType: onType,
          ),
        ),
      );
    }

    return commitWrites(
      context: context,
      writes: writes,
      message: 'Extension $extensionName on $onType generated.',
    );
  }

  String _isBlankBody(String onType) {
    switch (onType) {
      case 'String':
        return '    return trim().isEmpty;';
      case 'Iterable':
      case 'List':
      case 'Set':
        return '    return isEmpty;';
      case 'Map':
        return '    return isEmpty;';
      default:
        return '    return false;';
    }
  }

  String _test({
    required String project,
    required String snake,
    required String extensionName,
    required String onType,
  }) {
    if (onType == 'String') {
      return '''
import 'package:$project/extensions/$snake.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('$extensionName.isBlank', () {
    expect('  '.isBlank, isTrue);
    expect('x'.isBlank, isFalse);
  });
}
''';
    }
    return '''
import 'package:$project/extensions/$snake.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('$extensionName on $onType is declared', () {
    expect('$extensionName', equals('$extensionName'));
  });
}
''';
  }
}
