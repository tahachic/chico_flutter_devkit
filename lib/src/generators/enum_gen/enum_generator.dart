import '../../core/exceptions.dart';
import '../../fs/write_plan.dart';
import '../../naming/name_converter.dart';
import '../context.dart';
import '../result.dart';
import '../runner.dart';
import '../shared/generator_options.dart';

/// Generates a Dart enum with optional values.
final class EnumGenerator extends BaseGenerator {
  @override
  String get name => 'enum';

  @override
  String get description =>
      'Generate a Dart enum (optionally with --values a,b,c).';

  @override
  Future<void> validate(GenerationContext context) async {
    final values = GeneratorOptions.values(context);
    if (values.isEmpty) {
      throw const InvalidUsageException(
        'Enum values are required.',
        details:
            'Example: devkit generate enum OrderStatus --values pending,shipped,delivered',
      );
    }
    for (final value in values) {
      NameConverter.parse(value);
    }
  }

  @override
  Future<GenerationResult> generate(GenerationContext context) async {
    final pascal = context.targetName.pascalCase;
    final snake = context.targetName.snakeCase;
    final values = GeneratorOptions.values(context)
        .map((value) => NameConverter.parse(value).camelCase)
        .toList(growable: false);
    final generateTests = GeneratorOptions.wantsTests(context);

    final entries = values.map((value) => '  $value,').join('\n');
    final writes = <PlannedFileWrite>[
      PlannedFileWrite(
        relativePath: 'lib/enums/$snake.dart',
        content:
            '''
/// Generated by Chico Flutter DevKit — enum:$pascal
enum $pascal {
$entries
}

extension ${pascal}X on $pascal {
  String get wireName => name;
}
''',
      ),
    ];

    if (generateTests) {
      writes.add(
        PlannedFileWrite(
          relativePath: 'test/enums/${snake}_test.dart',
          content:
              '''
import 'package:${context.config.project.name}/enums/$snake.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('$pascal exposes values', () {
    expect($pascal.values, isNotEmpty);
    expect($pascal.${values.first}.wireName, '${values.first}');
  });
}
''',
        ),
      );
    }

    return commitWrites(
      context: context,
      writes: writes,
      message: 'Enum $pascal generated with ${values.length} value(s).',
    );
  }
}
