import '../../fs/write_plan.dart';
import '../context.dart';
import '../result.dart';
import '../runner.dart';
import '../shared/generated_test_support.dart';
import '../shared/generator_options.dart';

/// Generates a service interface + implementation.
final class ServiceGenerator extends BaseGenerator {
  @override
  String get name => 'service';

  @override
  String get description => 'Generate a service interface and implementation.';

  @override
  Future<void> validate(GenerationContext context) async {}

  @override
  Future<GenerationResult> generate(GenerationContext context) async {
    final rawPascal = context.targetName.pascalCase;
    final rawSnake = context.targetName.snakeCase;
    final pascal = rawPascal.endsWith('Service')
        ? rawPascal
        : '${rawPascal}Service';
    final snake = rawSnake.endsWith('_service')
        ? rawSnake
        : '${rawSnake}_service';
    final feature = GeneratorOptions.featureName(context);
    final generateTests = GeneratorOptions.wantsTests(context);

    final baseDir = feature == null
        ? 'lib/services'
        : 'lib/features/$feature/data/services';

    final writes = <PlannedFileWrite>[
      PlannedFileWrite(
        relativePath: '$baseDir/$snake.dart',
        content:
            '''
/// Generated by Chico Flutter DevKit — service interface
abstract interface class $pascal {
  Future<void> initialize();
  Future<void> dispose();
}
''',
      ),
      PlannedFileWrite(
        relativePath: '$baseDir/${snake}_impl.dart',
        content:
            '''
import '$snake.dart';

/// Generated by Chico Flutter DevKit — service implementation
class ${pascal}Impl implements $pascal {
  bool _ready = false;

  bool get isReady => _ready;

  @override
  Future<void> initialize() async {
    // Scaffold only — wire dependencies / clients for your domain.
    _ready = true;
  }

  @override
  Future<void> dispose() async {
    _ready = false;
  }
}
''',
      ),
    ];

    if (generateTests) {
      final testImport = GeneratedTestSupport.unitTestImport(
        isFlutter: GeneratedTestSupport.isFlutterProject(context.projectRoot),
      );
      writes.add(
        PlannedFileWrite(
          relativePath: feature == null
              ? 'test/services/${snake}_test.dart'
              : 'test/features/$feature/services/${snake}_test.dart',
          content:
              '''
import 'package:${context.config.project.name}/${feature == null ? 'services' : 'features/$feature/data/services'}/${snake}_impl.dart';
$testImport

void main() {
  test('${pascal}Impl initializes', () async {
    final service = ${pascal}Impl();
    await service.initialize();
    expect(service.isReady, isTrue);
    await service.dispose();
    expect(service.isReady, isFalse);
  });
}
''',
        ),
      );
    }

    return commitWrites(
      context: context,
      writes: writes,
      message: 'Service $pascal generated.',
    );
  }
}
