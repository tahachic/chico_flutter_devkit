import '../../core/exceptions.dart';
import '../../fs/write_plan.dart';
import '../context.dart';
import '../result.dart';
import '../runner.dart';
import '../shared/code_builders.dart';
import '../shared/field_spec.dart';
import 'json_model_inferrer.dart';

/// Generates an immutable Dart model with JSON / copyWith / equality.
final class ModelGenerator extends BaseGenerator {
  @override
  String get name => 'model';

  @override
  String get description =>
      'Generate a Dart model with fromJson, toJson, copyWith, and equality.';

  @override
  Future<void> validate(GenerationContext context) async {
    final fields = _resolveFields(context);
    if (fields.isEmpty) {
      throw const InvalidUsageException(
        'Model fields are required.',
        details:
            'Pass --fields id:String,name:String or --from-json path/to.json',
      );
    }
  }

  @override
  Future<GenerationResult> generate(GenerationContext context) async {
    final fields = _resolveFields(context);
    final className = context.targetName.pascalCase;
    final snake = context.targetName.snakeCase;
    final generateTests = _wantsTests(context);

    final modelSource = _renderModel(className: className, fields: fields);
    final writes = <PlannedFileWrite>[
      PlannedFileWrite(
        relativePath: 'lib/models/$snake.dart',
        content: modelSource,
      ),
    ];

    if (generateTests) {
      writes.add(
        PlannedFileWrite(
          relativePath: 'test/models/${snake}_test.dart',
          content: _renderTest(
            className: className,
            snake: snake,
            projectName: context.config.project.name,
            fields: fields,
          ),
        ),
      );
    }

    return commitWrites(
      context: context,
      writes: writes,
      message: 'Model $className generated with ${fields.length} field(s).',
    );
  }

  List<FieldSpec> _resolveFields(GenerationContext context) {
    final fromJson = context.extra['fromJson'] as String?;
    final fieldsRaw = context.extra['fields'] as String?;

    if (fromJson != null && fromJson.trim().isNotEmpty) {
      return JsonModelInferrer.fromJsonString(fromJson);
    }
    if (fieldsRaw != null) {
      return FieldSpec.parseList(fieldsRaw);
    }
    // Sensible default entity shape when callers omit fields (feature reuse).
    if (context.extra['allowDefaultFields'] == true) {
      return const [
        FieldSpec(name: 'id', type: 'String'),
        FieldSpec(name: 'name', type: 'String'),
      ];
    }
    return const [];
  }

  bool _wantsTests(GenerationContext context) {
    final flag = context.extra['tests'];
    if (flag is bool) return flag;
    return context.config.features.generateTests;
  }

  String _renderModel({
    required String className,
    required List<FieldSpec> fields,
  }) {
    return '''
/// Generated by Chico Flutter DevKit — model:$className
class $className {
  const $className(${CodeBuilders.constructorParams(fields)});

${CodeBuilders.fieldDeclarations(fields)}

${CodeBuilders.fromJson(className, fields)}

${CodeBuilders.toJson(fields)}

${CodeBuilders.copyWithBody(className, fields)}

${CodeBuilders.equality(className, fields)}

  @override
  String toString() => '$className(${fields.map((f) => '${f.name}: \$${f.name}').join(', ')})';
}
''';
  }

  String _renderTest({
    required String className,
    required String snake,
    required String projectName,
    required List<FieldSpec> fields,
  }) {
    final sampleArgs = fields
        .map((f) {
          return '      ${f.name}: ${_sampleValue(f)},';
        })
        .join('\n');
    final canBeConst = fields.every(
      (f) => f.type != 'DateTime' && !f.type.startsWith('List<'),
    );
    final keyword = canBeConst ? 'const' : 'final';

    return '''
import 'package:$projectName/models/$snake.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  group('$className', () {
    test('round-trips through JSON', () {
      $keyword model = $className(
$sampleArgs
      );
      final decoded = $className.fromJson(model.toJson());
      expect(decoded, model);
    });

    test('copyWith overrides fields', () {
      $keyword model = $className(
$sampleArgs
      );
      final copied = model.copyWith(${_firstCopyOverride(fields)});
      expect(copied, isNot(model));
    });
  });
}
''';
  }

  String _sampleValue(FieldSpec field) {
    switch (field.type) {
      case 'String':
        return field.isNullable ? 'null' : "'sample_${field.name}'";
      case 'int':
        return field.isNullable ? 'null' : '1';
      case 'double':
      case 'num':
        return field.isNullable ? 'null' : '1.0';
      case 'bool':
        return field.isNullable ? 'null' : 'true';
      case 'DateTime':
        return field.isNullable ? 'null' : 'DateTime.utc(2024, 1, 1)';
      default:
        if (field.type.startsWith('List<')) {
          return field.isNullable ? 'null' : 'const []';
        }
        if (field.type.startsWith('Map<')) {
          return field.isNullable ? 'null' : 'const <String, dynamic>{}';
        }
        return field.isNullable ? 'null' : 'null /* unsupported sample */';
    }
  }

  String _firstCopyOverride(List<FieldSpec> fields) {
    final field = fields.first;
    if (field.type == 'String') return "${field.name}: 'changed'";
    if (field.type == 'int') return '${field.name}: 99';
    if (field.type == 'bool') return '${field.name}: false';
    if (field.type == 'double' || field.type == 'num') {
      return '${field.name}: 9.9';
    }
    return '${field.name}: ${field.isNullable ? 'null' : _sampleValue(field)}';
  }
}
