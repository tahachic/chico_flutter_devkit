import '../shared/chico_dependency_guard.dart';
import '../shared/generated_test_support.dart';
import '../shared/ui_imports.dart';

/// Generates a reusable Flutter widget.
final class WidgetGenerator extends BaseGenerator {
  @override
  String get name => 'widget';

  @override
  String get description =>
      'Generate a Flutter widget (shared or feature-local).';

  @override
  Future<void> validate(GenerationContext context) async {
    await ChicoDependencyGuard.ensure(context: context);
  }

  @override
  Future<GenerationResult> generate(GenerationContext context) async {
    final className = context.targetName.pascalCase;
    final snake = context.targetName.snakeCase;
    final feature = context.extra['feature'] as String?;
    final generateTests = _wantsTests(context);
    final useChico = UiImports.useChico(context.config);

    final relativePath = feature == null || feature.trim().isEmpty
        ? 'lib/widgets/$snake.dart'
        : 'lib/features/${_snake(feature)}/presentation/widgets/$snake.dart';

    final writes = <PlannedFileWrite>[
      PlannedFileWrite(
        relativePath: relativePath,
        content: useChico
            ? _chicoWidget(className, context)
            : _materialWidget(className),
      ),
    ];

    if (generateTests) {
      final testPath = feature == null || feature.trim().isEmpty
          ? 'test/widgets/${snake}_test.dart'
          : 'test/features/${_snake(feature)}/widgets/${snake}_test.dart';
      writes.add(
        PlannedFileWrite(
          relativePath: testPath,
          content: _widgetTest(
            className: className,
            importPath: relativePath.replaceFirst(
              'lib/',
              'package:${context.config.project.name}/',
            ),
            config: context.config,
          ),
        ),
      );
    }

    return commitWrites(
      context: context,
      writes: writes,
      message: 'Widget $className generated.',
    );
  }

  bool _wantsTests(GenerationContext context) {
    final flag = context.extra['tests'];
    if (flag is bool) return flag;
    return context.config.features.generateTests;
  }

  String _snake(String value) {
    // Already validated names should be snake; tolerate passthrough.
    return value.trim().replaceAll('-', '_').replaceAll(' ', '_').toLowerCase();
  }

  String _materialWidget(String className) {
    return '''
import 'package:flutter/material.dart';

/// Generated by Chico Flutter DevKit — widget:$className
class $className extends StatelessWidget {
  const $className({
    super.key,
    required this.title,
    this.subtitle,
    this.onPressed,
  });

  final String title;
  final String? subtitle;
  final VoidCallback? onPressed;

  @override
  Widget build(BuildContext context) {
    return ListTile(
      title: Text(title),
      subtitle: subtitle == null ? null : Text(subtitle!),
      onTap: onPressed,
    );
  }
}
''';
  }

  String _chicoWidget(String className, GenerationContext context) {
    return '''
${UiImports.packageImport(context.config)}

/// Generated by Chico Flutter DevKit — widget:$className
class $className extends StatelessWidget {
  const $className({
    super.key,
    required this.title,
    this.subtitle,
    this.onPressed,
  });

  final String title;
  final String? subtitle;
  final VoidCallback? onPressed;

  @override
  Widget build(BuildContext context) {
    return ChicoListTile(
      title: title,
      subtitle: subtitle,
      onPressed: onPressed,
    );
  }
}
''';
  }

  String _widgetTest({
    required String className,
    required String importPath,
    required DevKitConfig config,
  }) {
    final imports = GeneratedTestSupport.widgetHarnessImports(
      config: config,
      underTestImport: importPath,
    );
    if (UiImports.useChico(config)) {
      return '''
$imports

void main() {
  testWidgets('$className renders title', (tester) async {
    await tester.pumpWidget(
      const ChicoApp(
        home: $className(title: 'Hello'),
      ),
    );
    expect(find.text('Hello'), findsOneWidget);
  });
}
''';
    }
    return '''
$imports

void main() {
  testWidgets('$className renders title', (tester) async {
    await tester.pumpWidget(
      const MaterialApp(
        home: Scaffold(
          body: $className(title: 'Hello'),
        ),
      ),
    );
    expect(find.text('Hello'), findsOneWidget);
  });
}
''';
  }
}
