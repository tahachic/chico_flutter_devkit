import '../../fs/write_plan.dart';
import '../context.dart';
import '../result.dart';
import '../runner.dart';
import '../shared/chico_dependency_guard.dart';
import '../shared/ui_imports.dart';

/// Generates a Flutter screen/page with optional state-management wiring.
final class ScreenGenerator extends BaseGenerator {
  @override
  String get name => 'screen';

  @override
  String get description =>
      'Generate a Flutter screen with optional state management hooks.';

  @override
  Future<void> validate(GenerationContext context) async {
    await ChicoDependencyGuard.ensure(context: context);
  }

  @override
  Future<GenerationResult> generate(GenerationContext context) async {
    final className = '${context.targetName.pascalCase}Page';
    final snake = '${context.targetName.snakeCase}_page';
    final feature = context.extra['feature'] as String?;
    final generateTests = _wantsTests(context);
    final state = context.config.flutter.stateManagement;
    final useChico = UiImports.useChico(context.config);

    final relativePath = feature == null || feature.trim().isEmpty
        ? 'lib/presentation/pages/$snake.dart'
        : 'lib/features/${_snake(feature)}/presentation/pages/$snake.dart';

    final writes = <PlannedFileWrite>[
      PlannedFileWrite(
        relativePath: relativePath,
        content: useChico
            ? _chicoScreen(className, state, context)
            : _materialScreen(className, state),
      ),
    ];

    if (generateTests) {
      writes.add(
        PlannedFileWrite(
          relativePath: feature == null || feature.trim().isEmpty
              ? 'test/presentation/pages/${snake}_test.dart'
              : 'test/features/${_snake(feature)}/pages/${snake}_test.dart',
          content: _screenTest(
            className: className,
            importPath: relativePath.replaceFirst(
              'lib/',
              'package:${context.config.project.name}/',
            ),
            useChico: useChico,
          ),
        ),
      );
    }

    return commitWrites(
      context: context,
      writes: writes,
      message: 'Screen $className generated (${state.yamlValue}).',
    );
  }

  bool _wantsTests(GenerationContext context) {
    final flag = context.extra['tests'];
    if (flag is bool) return flag;
    return context.config.features.generateTests;
  }

  String _snake(String value) =>
      value.trim().replaceAll('-', '_').replaceAll(' ', '_').toLowerCase();

  String _materialScreen(String className, StateManagement state) {
    final body = _stateHintComment(state);
    return '''
import 'package:flutter/material.dart';

/// Generated by Chico Flutter DevKit — screen:$className
class $className extends StatelessWidget {
  const $className({super.key});

  @override
  Widget build(BuildContext context) {
$body
    return Scaffold(
      appBar: AppBar(title: const Text('$className')),
      body: const Center(
        child: Text('$className'),
      ),
    );
  }
}
''';
  }

  String _chicoScreen(
    String className,
    StateManagement state,
    GenerationContext context,
  ) {
    final body = _stateHintComment(state);
    return '''
${UiImports.packageImport(context.config)}

/// Generated by Chico Flutter DevKit — screen:$className
class $className extends StatelessWidget {
  const $className({super.key});

  @override
  Widget build(BuildContext context) {
$body
    return ChicoScaffold(
      bar: const ChicoBar(title: '$className'),
      body: const ChicoPage(
        child: ChicoText('$className', variant: ChicoTextVariant.title),
      ),
    );
  }
}
''';
  }

  String _stateHintComment(StateManagement state) {
    return switch (state) {
      StateManagement.bloc || StateManagement.cubit =>
        '    // Wire Bloc/Cubit providers at the route or feature boundary.\n',
      StateManagement.riverpod =>
        '    // Prefer ConsumerWidget when connecting Riverpod providers.\n',
      StateManagement.provider =>
        '    // Wrap with ChangeNotifierProvider when connecting Provider.\n',
    };
  }

  String _screenTest({
    required String className,
    required String importPath,
    required bool useChico,
  }) {
    if (useChico) {
      return '''
import 'package:flutter_test/flutter_test.dart';
import '$importPath';

void main() {
  testWidgets('$className builds', (tester) async {
    await tester.pumpWidget(const ChicoApp(home: $className()));
    expect(find.text('$className'), findsWidgets);
  });
}
''';
    }
    return '''
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import '$importPath';

void main() {
  testWidgets('$className builds', (tester) async {
    await tester.pumpWidget(const MaterialApp(home: $className()));
    expect(find.text('$className'), findsWidgets);
  });
}
''';
  }
}
